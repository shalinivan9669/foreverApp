function material(
  seed: DomainSeed,
  kind: DevelopmentKind,
  index: number,
  title: string,
  steps: string[],
  prompts: string[] = [],
): DevelopmentContent {
  return {
    key: `${seed.domain}.${kind.toLowerCase()}.${index + 1}`,
    revision: 1,
    domain: seed.domain,
    kind,
    title,
    purpose: DEVELOPMENT_DOMAINS.find((domain) => domain.key === seed.domain)!
      .description,
    durationMinutes: kind === "REFLECTION" ? 4 : kind === "LEISURE" ? 20 : 10,
    steps,
    prompts,
    conditions:
      "Добровольно, в спокойной обстановке. Любой вопрос или занятие можно пропустить. Не подходит для разрешения острой или небезопасной ситуации.",
    outcome:
      kind === "REFLECTION"
        ? "Личные наблюдения и выбор следующей практики; без диагноза и оценки совместимости."
        : "Отметка о выполнении и личная обратная связь. Сам факт выполнения не доказывает рост навыка.",
    reviewStatus: "DEMO_SELF_REFLECTION",
  };
}

